export const DEFAULT_DISCLAIMER_BODY =
  "This Information Memorandum has been prepared using information supplied by the seller and app-connected data sources where available. It is provided for general information only and does not constitute financial, legal or accounting advice. Buyers must conduct their own due diligence and obtain independent professional advice before making any decision to purchase. Valuation outputs are indicative only and are based on selected assumptions, data inputs, valuation multiples, and seller-supplied information.";

/**
 * Returns the 40 default section insert records for a given listing.
 * Sections with stable default body text (e.g. disclaimer) are pre-populated.
 */
export function buildDefaultSections(listingId: string, ownerId: string) {
  return SECTION_DEFAULTS.map((def) => ({
    listingId,
    ownerId,
    sectionKey:      def.sectionKey,
    title:           def.title,
    subtitle:        def.subtitle,
    body:            def.sectionKey === "disclaimer" ? DEFAULT_DISCLAIMER_BODY : "",
    bulletPoints:    [] as string[],
    aiInstruction:   def.aiInstruction,
    visibility:      def.visibility,
    includeInPdf:    def.includeInPdf,
    includeInHtml:   def.includeInHtml,
    includeInApp:    def.includeInApp,
    sortOrder:       def.sortOrder,
    isRequired:      def.isRequired,
    isAutoGenerated: def.isAutoGenerated,
    isAiEditable:    true,
    status:          def.sectionKey === "disclaimer" ? "complete" : "empty",
    dataSource:      "seller_supplied",
  }));
}
